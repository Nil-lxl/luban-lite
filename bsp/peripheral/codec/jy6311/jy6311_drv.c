void jy6311_drv_volume_set(struct codec *codec, uint8_t volume)
{
    uint8_t reg_value = 0;

    JY6311_LOG_I("--->%s\n", __FUNCTION__);

    if (volume == 0) {
        // Mute handling
        reg_value = 0x00;  // Mute
    } else if (volume >= 100) {
        // Maximum volume
        reg_value = 0xBF;  // 0dB
    } else {
        // Map 1-100 to 0x01-0xBF (corresponding to -95dB to 0dB)
        // Use linear interpolation: (volume-1) * 190 / 99
        reg_value = 0x01 + (uint8_t)((volume - 1) * 190 / 99);

        // Ensure value is within valid range
        if (reg_value < 0x01) reg_value = 0x01;
        if (reg_value > 0xBF) reg_value = 0xBF;
    }

    /* Set playback and recording volume */
    jy6311_play_vol_cfg(JY6311_I2C_ADDR, reg_value);
    // jy6311_record_vol_cfg(JY6311_I2C_ADDR, reg_value);
}

uint8_t jy6311_drv_volume_get(struct codec *codec)
{
    JY6311_LOG_I("--->%s\n", __FUNCTION__);

    uint8_t current_reg_value = 0;
    uint8_t volume = 0;

    // Read current register value from chip
    current_reg_value = jy6311_get_vol_cfg(JY6311_I2C_ADDR);

    if (current_reg_value == 0x00) {
        // Mute state
        volume = 0;
    } else if (current_reg_value >= 0xBF) {
        // Maximum volume
        volume = 100;
    } else {
        // Reverse calculation: map register value back to 1-100 range
        // Original formula: reg_value = 0x01 + (volume - 1) * 190 / 99
        // Reverse: volume = (reg_value - 0x01) * 99 / 190 + 1
        volume = (uint8_t)(((current_reg_value - 0x01) * 99) / 190) + 1;

        // Ensure volume is within valid range
        if (volume > 100) volume = 100;
        if (volume < 1) volume = 1;
    }

    return volume;
}



void jy6311_drv_pa_power(struct codec *codec, uint8_t enable)
{
    uint32_t power_pin = 0;

    JY6311_LOG_I("--->%s\n", __FUNCTION__);

    power_pin = rt_pin_get(AIC_I2S_CODEC_PA_PIN);
    rt_pin_mode(power_pin, PIN_MODE_OUTPUT);

    if (enable)
        rt_pin_write(power_pin, PIN_HIGH);
    else
        rt_pin_write(power_pin, PIN_LOW);
}

void jy6311_drv_dump_reg(struct codec *codec)
{
    uint8_t value;
    int i;

    JY6311_LOG_I("--->%s\n", __FUNCTION__);

    for (i = 0; i < 0x85; i++) {
        value = jy6311_i2c_read_byte(JY6311_I2C_ADDR, i);

        if (i % 16 == 0)
            rt_kprintf("0x%02x: ", i);

        rt_kprintf("0x%02x   ", value);

        if ((i + 1) % 16 == 0)
            rt_kprintf("\n");
    }

    rt_kprintf("\n");
}

