void jy6311_drv_set_voice_mute(uint8_t enable)
{
    JY6311_LOG_I("--->%s\n", __FUNCTION__);
    /* Set volume to mute */
    jy6311_play_vol_cfg(JY6311_I2C_ADDR, 0x00);
    jy6311_record_vol_cfg(JY6311_I2C_ADDR, 0x00);
}

int jy6311_drv_init(struct codec *codec)
{
    JY6311_LOG_I("--->%s\n", __FUNCTION__);

    return RT_EOK;
}

int jy6311_drv_start(struct codec *codec, i2s_stream_t stream)
{
    JY6311_LOG_I("--->%s\n", __FUNCTION__);

    ARG_UNUSED(codec);

    if (!stream)
        jy6311_example_play();
    else
        jy6311_example_record();
    return 0;
}

int jy6311_drv_stop(struct codec *codec, i2s_stream_t stream)
{
    JY6311_LOG_I("--->%s\n", __FUNCTION__);

    if (!stream) {
        // JY6311 Play Stop
        jy6311_play_stop(JY6311_I2C_ADDR);
        /* [Optional] DAC Optional Configuration, eg Volume/EQ/DRC */
        jy6311_play_vol_cfg(JY6311_I2C_ADDR, 0xBF);                      // DAC Digital Volume 0dB
        jy6311_dac_eq_cfg(JY6311_I2C_ADDR, false, NULL, 0);
        jy6311_dac_drc_cfg(JY6311_I2C_ADDR, false, NULL, 0);
        //JY6311 DeInit
        jy6311_deinit(JY6311_I2C_ADDR, JY6311_INIT_MOD_DAC);
    } else {
        // JY6311 Record Stop
        jy6311_record_stop(JY6311_I2C_ADDR);
        /* [Optional] ADC Optional Configuration, eg Gain/EQ/DRC */
        jy6311_record_gain_cfg(JY6311_I2C_ADDR, JY6311_ADC_PGA_GAIN_0dB);// ADC PGA Gain 0dB
        jy6311_adc_eq_cfg(JY6311_I2C_ADDR, false, NULL, 0);
        jy6311_adc_drc_cfg(JY6311_I2C_ADDR, false, NULL, 0);
        // JY6311 DeInit
        jy6311_deinit(JY6311_I2C_ADDR, JY6311_INIT_MOD_ADC);
    }

    return 0;
}

int jy6311_drv_set_protocol(struct codec *codec, i2s_format_t *format)
{
    JY6311_LOG_I("--->%s\n", __FUNCTION__);

    switch (format->protocol)
    {
    case I2S_PCM_LONG:
        g_jy6311_i2s_cfg.fmt = JY6311_I2S_FMT_PCM_A;
        break;
    case I2S_PCM_SHORT:
        g_jy6311_i2s_cfg.fmt = JY6311_I2S_FMT_PCM_B;
        break;
    case I2S_PROTOCOL_LEFT_J:
        g_jy6311_i2s_cfg.fmt = JY6311_I2S_FMT_LEFT_J;
        break;
    case I2S_PROTOCOL_I2S:
    default:
        g_jy6311_i2s_cfg.fmt = JY6311_I2S_FMT_I2S;
        break;
    }

    return 0;
}

int jy6311_drv_set_polarity(struct codec *codec, i2s_format_t *format)
{
    JY6311_LOG_I("--->%s\n", __FUNCTION__);

    switch (format->polarity)
    {
    case I2S_LEFT_POLARITY_HIGH:
        g_jy6311_i2s_cfg.lrck_invert = true;
        g_jy6311_i2s_cfg.bclk_invert = true;
        break;
    case I2S_LEFT_POLARITY_LOW:
    default:
        g_jy6311_i2s_cfg.lrck_invert = false;
        g_jy6311_i2s_cfg.bclk_invert = false;
        break;
    }

    return 0;
}

