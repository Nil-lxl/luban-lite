#include "panel_com.h"
#include "panel_dsi.h"

static int panel_enable(struct aic_panel *panel)
{
    int ret;

    panel_di_enable(panel, 0);
    panel_dsi_send_perpare(panel);

    panel_dsi_dcs_send_seq(panel, 0x10);
    panel_dsi_dcs_send_seq(panel, 0x28);

    panel_dsi_generic_send_seq(panel, 0x99, 0x71, 0x02, 0xa2);
    panel_dsi_generic_send_seq(panel, 0x99, 0x71, 0x02, 0xa3);
    panel_dsi_generic_send_seq(panel, 0x99, 0x71, 0x02, 0xa4);

    panel_dsi_dcs_send_seq(panel, 0x78, 0x21);
    panel_dsi_dcs_send_seq(panel, 0x79, 0xCF);

    panel_dsi_dcs_send_seq(panel, 0xB0, 0x22, 0x57, 0x1E, 0x61, 0x2F, 0x57, 0x61);
    panel_dsi_dcs_send_seq(panel, 0xB7, 0x64, 0x64);
    panel_dsi_dcs_send_seq(panel, 0xBF, 0x6e, 0x6e);

    panel_dsi_generic_send_seq(panel, 0xC8, 0x00, 0x00, 0x13, 0x23, 0x3E, 0x00, 0x6A,
                             0x03, 0xB0, 0x06, 0x11, 0x0F, 0x07, 0x85, 0x03, 0x21,
                             0xD5, 0x01, 0x18, 0x00, 0x22, 0x56, 0x0F, 0x98, 0x0A,
                             0x32, 0xF8, 0x0D, 0x48, 0x0F, 0xF3, 0x80, 0x0F, 0xAC,
                             0xC1, 0x03, 0xC4);
    panel_dsi_generic_send_seq(panel, 0xC9, 0x00, 0x00, 0x13, 0x23, 0x3E, 0x00, 0x6A,
                             0x03, 0xB0, 0x06, 0x11, 0x0F, 0x07, 0x85, 0x03, 0x21,
                             0xD5, 0x01, 0x18, 0x00, 0x22, 0x56, 0x0F, 0x98, 0x0A,
                             0x32, 0xF8, 0x0D, 0x48, 0x0F, 0xF3, 0x80, 0x0F, 0xAC,
                             0xC1, 0x03, 0xC4);

    panel_dsi_dcs_send_seq(panel, 0xD7, 0x10, 0x0C, 0x77, 0x19, 0xE0, 0xE0);

    panel_dsi_dcs_send_seq(panel, 0xA3, 0x40, 0x03, 0x80, 0xCF, 0x44, 0x00, 0x00,
                           0x00, 0x00, 0x04, 0x6F, 0x6F, 0x00, 0x1A, 0x00, 0x45,
                           0x05, 0x00, 0x00, 0x00, 0x00, 0x46, 0x00, 0x00, 0x02,
                           0x20, 0x52, 0x00, 0x05, 0x00, 0x00, 0xFF);

    panel_dsi_dcs_send_seq(panel, 0xA6, 0x02, 0x00, 0x24, 0x55, 0x35, 0x00, 0x38,
                           0x00, 0x5E, 0x5E, 0x00, 0x24, 0x55, 0x36, 0x00, 0x37,
                           0x00, 0x5E, 0x5E, 0x02, 0xAC, 0x51, 0x3A, 0x00, 0x00,
                           0x00, 0x5E, 0x5E, 0x00, 0xAC, 0x11, 0x00, 0x00, 0x00,
                           0x00, 0x5E, 0x5E, 0x00, 0x00, 0x06, 0x00, 0x00, 0x00,
                           0x00);

    panel_dsi_dcs_send_seq(panel, 0xA7, 0x19, 0x19, 0x00, 0x64, 0x40, 0x07, 0x16,
                           0x40, 0x00, 0x04, 0x03, 0x5E, 0x5E, 0x00, 0x64, 0x40,
                           0x25, 0x34, 0x00, 0x00, 0x02, 0x01, 0x5E, 0x5E, 0x00,
                           0x64, 0x40, 0x4B, 0x5A, 0x00, 0x00, 0x02, 0x01, 0x5E,
                           0x5E, 0x00, 0x24, 0x40, 0x69, 0x78, 0x00, 0x00, 0x00,
                           0x00, 0x5E, 0x5E, 0x00, 0x44);

    panel_dsi_dcs_send_seq(panel, 0xAC, 0x08, 0x0A, 0x11, 0x00, 0x13, 0x03, 0x1B,
                           0x18, 0x06, 0x1A, 0x19, 0x1B, 0x1B, 0x1B, 0x18, 0x1B,
                           0x09, 0x0B, 0x10, 0x02, 0x12, 0x01, 0x1B, 0x18, 0x06,
                           0x1A, 0x19, 0x1B, 0x1B, 0x1B, 0x18, 0x1B, 0xFF, 0x67,
                           0xFF, 0x67, 0x00);

    panel_dsi_dcs_send_seq(panel, 0xAD, 0xCC, 0x40, 0x46, 0x11, 0x04, 0x6F, 0x6F);

    panel_dsi_dcs_send_seq(panel, 0xE8, 0x30, 0x07, 0x00, 0x7A, 0x7A, 0x9C, 0x00,
                           0xE2, 0x04, 0x00, 0x00, 0x00, 0x00, 0xEF);

    panel_dsi_generic_send_seq(panel, 0x75, 0x03, 0x04);

    panel_dsi_dcs_send_seq(panel, 0xE7, 0x8B, 0x3C, 0x00, 0x0C, 0xF0, 0x5D, 0x00,
                           0x5D, 0x00, 0x5D, 0x00, 0x5D, 0x00, 0xFF, 0x00, 0x08,
                           0x7B, 0x00, 0x00, 0xC8, 0x6A, 0x5A, 0x08, 0x1A, 0x3C,
                           0x00, 0x91, 0x01, 0xCC, 0x01, 0x7F, 0xF0, 0x22);

    panel_dsi_dcs_send_seq(panel, 0xE9, 0x4C, 0x7F, 0x08, 0x07, 0x1A, 0x7A, 0x22,
                           0x1A, 0x33);

    /* mipi.write 0x05 0x11 / 0x29 */
    ret = panel_dsi_dcs_exit_sleep_mode(panel);
    if (ret < 0) {
        pr_err("Failed to exit sleep mode: %d\n", ret);
        return ret;
    }
    aic_delay_ms(120);

    ret = panel_dsi_dcs_set_display_on(panel);
    if (ret < 0) {
        pr_err("Failed to set display on: %d\n", ret);
        return ret;
    }

    panel_dsi_generic_send_seq(panel, 0x35, 0x00);

    panel_dsi_setup_realmode(panel);

    panel_de_timing_enable(panel, 0);
    panel_backlight_enable(panel, 0);
    return 0;
}

static struct aic_panel_funcs panel_funcs = {
    .disable = panel_default_disable,
    .unprepare = panel_default_unprepare,
    .prepare = panel_default_prepare,
    .enable = panel_enable,
    .register_callback = panel_register_callback,
};

static struct display_timing st7102_timing = {
    .pixelclock = 33 * 1000000,
    .hactive = 480,
    .hfront_porch = 40,
    .hback_porch = 40,
    .hsync_len = 2,

    .vactive = 960,
    .vfront_porch = 10,
    .vback_porch = 10,
    .vsync_len = 2,
};

struct panel_dsi dsi = {
    .mode = DSI_MOD_VID_BURST,
    .format = DSI_FMT_RGB888,
    .lane_num = 2,
};

struct aic_panel dsi_st7102 = {
    .name = "panel-dsi-st7102",
    .timings = &st7102_timing,
    .funcs = &panel_funcs,
    .dsi = &dsi,
    .connector_type = AIC_MIPI_COM,
};
