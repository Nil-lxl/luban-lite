/*
 * Date flow:
 *
 * Hardware --> [Interrupt] --> [Timer] --> [Thread] --> LVGL
 *                    ^           |            |
 *                    |           v            |
 *                    +----[Status Flags] <----+
*/

static void lv_aic_mouse_cleanup(void);
static void lv_aic_mouse_timer_cb(lv_timer_t *timer);
static void lv_aic_mouse_entry(void *p);
static int lv_aic_mouse_x_convert(int last_value, uint8_t value, float zoom);
static int lv_aic_mouse_y_convert(int last_value, uint8_t value, float zoom);
static int lv_aic_mouse_encoder_convert(uint8_t value);
static void lv_aic_mouse_read(lv_indev_t * indev, lv_indev_data_t * data);

typedef enum {
    USB_STATUS_REMOVED = 0,
    USB_STATUS_INSERTED,
} usb_status_t;

typedef struct {
    volatile int16_t last_x;
    volatile int16_t last_y;
    volatile bool left_button_down;
    volatile int32_t diff;
    rt_device_t dev;

    lv_timer_t *timer;
    lv_obj_t *mouse_cursor;
    volatile bool thread_should_exit;
    volatile bool mouse_device_created;
    volatile usb_status_t usb_status;
    lv_indev_t *indev;
    float mouse_sensitivity;
} lv_aic_mouse_t;

static lv_aic_mouse_t mouse_dsc = {
    .last_x = 0,
    .last_y = 0,
    .left_button_down = false,
    .diff = 0,
    .dev = NULL,
    .timer = NULL,
    .mouse_cursor = NULL,
    .thread_should_exit = false,
    .mouse_device_created = false,
    .usb_status = USB_STATUS_REMOVED,
    .indev = NULL,
    .mouse_sensitivity = 1.0f,
};

void aicusbh_hid_hotplug_irq(char *name, int32_t hotplug)
{
    rt_kprintf("[I/usbh_hid] name = %s, hotplug = %d\n", name, hotplug);
    if (hotplug == USB_STATUS_INSERTED) {
        if (strncmp(name, "mouse", strlen("mouse")) == 0) {
            mouse_dsc.usb_status = USB_STATUS_INSERTED;
        }
    } else {
        if (strncmp(name, "mouse", strlen("mouse")) == 0) {
            mouse_dsc.usb_status = USB_STATUS_REMOVED;
        }
    }
}

void lv_aic_mouse_hotplug_init(void)
{
    mouse_dsc.timer = lv_timer_create(lv_aic_mouse_timer_cb, 20, NULL);
}

static void lv_aic_mouse_cleanup(void)
{
    if (mouse_dsc.indev) {
        lv_indev_delete(mouse_dsc.indev);
    }

    if (mouse_dsc.mouse_cursor) {
        lv_obj_del(mouse_dsc.mouse_cursor);
    }

    mouse_dsc.mouse_cursor = NULL;
    mouse_dsc.indev = NULL;
    mouse_dsc.mouse_device_created = false;
    mouse_dsc.thread_should_exit = false;
}

static void lv_aic_mouse_timer_cb(lv_timer_t *timer)
{
    if (mouse_dsc.usb_status == USB_STATUS_INSERTED && mouse_dsc.mouse_device_created == false) {
        mouse_dsc.indev = lv_indev_create();
        if(mouse_dsc.indev == NULL) {
            return;
        }

        lv_indev_set_type(mouse_dsc.indev, LV_INDEV_TYPE_POINTER);
        lv_indev_set_read_cb(mouse_dsc.indev, lv_aic_mouse_read);
        lv_indev_set_driver_data(mouse_dsc.indev, NULL);

        mouse_dsc.mouse_cursor = lv_image_create(lv_layer_top());
        if (mouse_dsc.mouse_cursor == NULL) {
            LV_LOG_ERROR("Failed to create cursor");
            lv_aic_mouse_cleanup();
            return;
        }
        lv_image_set_src(mouse_dsc.mouse_cursor, &mouse_cursor_icon);
        lv_indev_set_cursor(mouse_dsc.indev, mouse_dsc.mouse_cursor);
        lv_obj_set_pos(mouse_dsc.mouse_cursor, mouse_dsc.last_x, mouse_dsc.last_y);

        rt_thread_t thread = rt_thread_create("lv_aic_mouse", lv_aic_mouse_entry, NULL,
                                            4096, 20, 10);
        if (thread == RT_NULL) {
            lv_aic_mouse_cleanup();
            return;
        }
        rt_thread_startup(thread);

        mouse_dsc.thread_should_exit = false;
        mouse_dsc.mouse_device_created = true;

        LV_LOG_INFO("create lvgl mouse indev");
    } else if (mouse_dsc.usb_status == USB_STATUS_REMOVED && mouse_dsc.mouse_device_created == 1) {
        mouse_dsc.thread_should_exit = true;
        lv_aic_mouse_cleanup();
        LV_LOG_INFO("delete lvgl mouse indev");
    }
}

static void lv_aic_mouse_read(lv_indev_t * indev, lv_indev_data_t * data)
{
    /*Store the collected data*/
    data->point.x = mouse_dsc.last_x;
    data->point.y = mouse_dsc.last_y;
    data->state = mouse_dsc.left_button_down ? LV_INDEV_STATE_PRESSED : LV_INDEV_STATE_RELEASED;
    data->enc_diff = mouse_dsc.diff;
    mouse_dsc.diff = 0;
}

static void lv_aic_mouse_entry(void *p)
{
    uint8_t buffer[4];
    int ret = 0;

    mouse_dsc.dev = rt_device_find("mouse");
    if (mouse_dsc.dev == RT_NULL)
    {
        rt_kprintf("can't find device:%s\n", "mouse");
        return;
    }

    if (rt_device_open(mouse_dsc.dev, 0) != RT_EOK)
    {
        rt_kprintf("Failed to open dev %s\n", "mouse");
        mouse_dsc.dev = NULL;
        return;
    }

    while (!mouse_dsc.thread_should_exit) {
        if (mouse_dsc.usb_status == USB_STATUS_INSERTED) {
            memset(buffer, 0, sizeof(buffer));
            ret = rt_device_read(mouse_dsc.dev, 0, buffer, 4);
            if (ret <= 0) {
                break;
            }

            mouse_dsc.left_button_down = buffer[0];
            mouse_dsc.last_x = lv_aic_mouse_x_convert(mouse_dsc.last_x, buffer[1], mouse_dsc.mouse_sensitivity);
            mouse_dsc.last_y = lv_aic_mouse_y_convert(mouse_dsc.last_y, buffer[2], mouse_dsc.mouse_sensitivity);
            mouse_dsc.diff = lv_aic_mouse_encoder_convert(buffer[3]);
        } else {
            rt_thread_mdelay(5);
        }
    }

    if (mouse_dsc.dev) {
        rt_device_close(mouse_dsc.dev);
        mouse_dsc.dev = NULL;
    }

    /* the system automatically reclaims thread resources. */
}

static int lv_aic_mouse_x_convert(int last_value, uint8_t value, float zoom)
{
    int coord_x = last_value;
    int true_value = value;

    if (value > 127)
        true_value = (value - 256) * zoom;

    coord_x += true_value;

    coord_x = LV_CLAMP(0, coord_x, LV_HOR_RES - 1);

    return coord_x;
}

static int lv_aic_mouse_y_convert(int last_value, uint8_t value, float zoom)
{
    int coord_y = last_value;
    int true_value = value;

    if (value > 127)
        true_value = (value - 256) * zoom;

    coord_y += true_value;

    coord_y = LV_CLAMP(0, coord_y, LV_VER_RES - 1);


    return coord_y;
}

static int lv_aic_mouse_encoder_convert(uint8_t value)
{
    int true_value = value;
    if (value > 127)
        true_value = value - 256;
    return true_value;
}

